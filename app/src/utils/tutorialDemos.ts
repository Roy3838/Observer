/** The tab title the demo page sets for itself (see demo-contract.js `?title=`). */
export const demoTabTitle = (d: TutorialDemo): string => `${d.title} · Observer demo`;

export const demoUrl = (d: TutorialDemo): string => {
  const q = new URLSearchParams({ outcome: 'success', tutorial: String(DEMO_RUN_MS), title: d.title });
  return `${DEMO_ORIGIN}${d.file}?${q}`;
};
