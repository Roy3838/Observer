// src/utils/tutorialDemos.ts
//
// The demos offered by the first-run tutorial (DemoPickerSplash). Each is one of the MCP e2e
// suite's demo pages (app/e2e/demos/), hosted on the landing site at observer-ai.com/demos/
// by websites/landing/scripts/sync-showcase.mjs. The tutorial opens one in a new tab in tutorial
// mode (demo-contract.js `?tutorial=`): it holds until the user comes back to it after sharing it
// with Observer, then succeeds DEMO_RUN_MS later. Observer watches it like any real screen.
//
// Titles match app/e2e/showcase.ts; prompt fragments follow the e2e prompts in scenarios.ts.
// Previews are generated by app/e2e/previews.ts into public/demo-previews/.

import type { TriggerOption } from '@components/AICreator/RecipeSplash';

export interface TutorialDemo extends TriggerOption {
  /** Demo page file name in e2e/demos/. */
  file: string;
  /** What it's called on the site and in the tab title: "GitHub Actions". */
  title: string;
  /** Full-size screenshot shown above the wheel while this demo is in focus. */
  preview: string;
}

const DEMO_ORIGIN = 'https://observer-ai.com/demos/';
// Long enough to watch it run, short enough not to wait around.
const DEMO_RUN_MS = 30000;

const demo = (file: string, title: string, label: string, promptFragment: string): TutorialDemo => ({
  id: file.replace(/\.html$/, ''),
  file,
  title,
  label,
  promptFragment,
  sensor: '$SCREEN',
  preview: `/demo-previews/${file.replace(/\.html$/, '.jpg')}`,
});

